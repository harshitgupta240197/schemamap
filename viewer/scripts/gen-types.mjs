// Generates src/generated/* from ../schema/snapshot.v1.json:
//   snapshot.ts           TypeScript types (json-schema-to-typescript)
//   validate-snapshot.js  Ajv standalone validator, precompiled so the viewer needs no
//                         runtime code generation (no `new Function`, CSP-safe)
//   validate-snapshot.d.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "generated");
const schema = JSON.parse(readFileSync(join(root, "..", "schema", "snapshot.v1.json"), "utf8"));
const banner = "Generated by scripts/gen-types.mjs from schema/snapshot.v1.json. Do not edit.";

mkdirSync(out, { recursive: true });

const types = await compile(schema, "Snapshot", {
  bannerComment: `/* ${banner} */`,
  additionalProperties: true,
  format: false,
});
writeFileSync(join(out, "snapshot.ts"), types);

// Formats (date-time) are not asserted: the viewer treats them as display strings, and
// asserting them would pull a runtime dependency into the standalone module.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  validateFormats: false,
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);
const requireUcs2 = 'const func1 = require("ajv/dist/runtime/ucs2length").default;';
const standalone = standaloneCode(ajv, validate);
if (!standalone.includes(requireUcs2)) {
  throw new Error("Unexpected Ajv standalone output: ucs2length require not found");
}
// Ajv emits a CommonJS require for its one runtime helper even in ESM mode; make it an import.
const code = `import ucs2length from "ajv/dist/runtime/ucs2length.js";\n${standalone.replace(requireUcs2, "const func1 = ucs2length;")}`;
writeFileSync(join(out, "validate-snapshot.js"), `// ${banner}\n// @ts-nocheck\n${code}`);
writeFileSync(
  join(out, "validate-snapshot.d.ts"),
  `/* ${banner} */
import type { ErrorObject } from "ajv";

declare const validate: {
  (data: unknown): boolean;
  errors?: ErrorObject[] | null;
};
export default validate;
`,
);
